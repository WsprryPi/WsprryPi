'use strict';
const assert = require('node:assert/strict');
const {browser,response,context,config} = require('./wtp_management_fixture.js');
const {schedules,changes} = require('../data/wtp-management.js');
(async()=>{
  assert.deepEqual(schedules(''), []);
  assert.throws(()=>schedules('121 0'));
  assert.deepEqual(changes(config,{version:1,enabled:false,station:config.station,wifi:config.wifi,schedules:config.schedules,expires_utc_s:0}),{});
  let fail=false, reboot=false;
  const b=browser(r=>fail ? response({error:{code:'revision_conflict'}},412) : response({...context(),reboot_required:reboot}));
  await b.click('wtp-remote-load');
  assert.equal(b.element('wtp-remote-callsign').value,'AA0NT');
  await b.click('wtp-remote-save'); assert.equal(b.requests.length,1);
  b.element('wtp-remote-callsign').value='K1ABC';
  await b.click('wtp-remote-save');
  assert.equal(b.requests.at(-1).method,'POST');
  assert.equal(b.requests.at(-1).url,'/api/v1/member/configuration');
  assert.deepEqual(b.requests.at(-1).body.config,{station:{callsign:'K1ABC'}});
  assert.match(b.element('wtp-management-feedback').textContent,/without a restart/);
  b.element('wtp-remote-password').value='private-draft'; fail=true;
  await b.click('wtp-remote-save');
  assert.match(b.element('wtp-management-feedback').textContent,/changed elsewhere/);
  assert.equal(b.element('wtp-remote-password').value,'private-draft');
  assert(b.element('wtp-remote-save').disabled);
  const count=b.requests.length; await b.click('wtp-remote-save'); assert.equal(b.requests.length,count);
  fail=false; await b.click('wtp-remote-load');
  assert.equal(b.element('wtp-remote-callsign').value,'K1ABC');
  assert.equal(b.element('wtp-remote-password').value,'private-draft');
  assert.match(b.element('wtp-remote-callsign-hint').textContent,/Saved: AA0NT/);
  assert.match(b.element('wtp-management-feedback').textContent,/draft and password entry are preserved/);
  reboot=true; await b.click('wtp-schedules-save');
  assert.equal(b.element('wtp-remote-password').value,'private-draft');
  assert.deepEqual(Object.keys(b.requests.at(-1).body.config),['schedules']);
  assert.match(b.element('wtp-management-feedback').textContent,/require a Pico restart/);
  await b.click('wtp-remote-save'); assert.equal(b.element('wtp-remote-password').value,'');
  let disconnected=false;
  const loss=browser(()=>{ if(disconnected) throw new Error('network failure'); return response(context()); });
  await loss.click('wtp-remote-load'); loss.element('wtp-remote-ssid').value='changed'; disconnected=true;
  await loss.click('wtp-remote-save'); assert(loss.element('wtp-remote-save').disabled);
  assert.equal(loss.element('wtp-remote-ssid').value,'changed');
  assert.equal(loss.requests.filter(r=>r.method==='POST').length,1);
  disconnected=false; await loss.click('wtp-remote-load');
  assert.equal(loss.element('wtp-remote-ssid').value,'changed');
  console.log('Pico settings producer, partial edits, no-change, drafts, conflict/readback, password and restart feedback passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
