#!/usr/bin/env python3
"""Generate the one current Pi-only authentication contract, independently of Control/1."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/wtp_integration/contract/pair-1.schema.json"
OUTPUT = ROOT / "src/wtp_integration/pi_pair_contract_data.hpp"


def generated():
    spec = json.loads(SOURCE.read_text())
    if (spec["contract"] != "Wsprry-Pair/1" or spec["$id"] != "urn:wsprry:pair:1" or
            spec["namespace"] != "/api/pair/v1/" or spec["maximum_body_bytes"] != 4096 or
            spec["maximum_nesting"] != 8 or spec["suite"] != "SPAKE2+-P256-SHA256-HKDF-HMAC"):
        raise ValueError("Unsupported pairing identity, profile, or bounds")
    expected = {
        "bootstrap": {"GET": ["window"], "POST": ["hello", "exchange", "confirm", "commit"]},
        "management": {"GET": ["operations/{operation_id}", "resume"],
                       "POST": ["rotate/prepare", "rotate/commit", "authorities/register", "resume/ack"]},
        "retirement": {"POST": ["retirement", "retirement/status"]}}
    if spec["routes"] != expected or len(spec["documents"]) != len(set(spec["documents"])):
        raise ValueError("Pairing purpose/route registry differs")
    for name in spec["documents"]:
        rule = spec["$defs"][name]
        if (rule.get("additionalProperties") is not False or
                set(rule["required"]) != set(rule["properties"]) or
                rule["properties"]["contract"] != {"const": "Wsprry-Pair/1"}):
            raise ValueError("Pairing messages must have one exact closed current shape")
    body = json.dumps(spec, separators=(",", ":"))
    if len(body) > 262144 or ')PAIR"' in body:
        raise ValueError("Pairing registry exceeds generation bound")
    header = "// Generated by scripts/generate_pair_contract.py; edit pair-1.schema.json.\n"
    header += "#pragma once\n#include <string>\n#include <string_view>\nnamespace wsprrypi {\n"
    header += "inline std::string_view pi_pair_contract_data() {\n  static const std::string document = [] {\n    std::string value; value.reserve(" + str(len(body)) + ");\n"
    for offset in range(0, len(body), 16384):
        header += '    value.append(R"PAIR(' + body[offset:offset + 16384] + ')PAIR");\n'
    return header + "    return value;\n  }();\n  return document;\n}\n}\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise ValueError("Stale generated Pi pairing contract")
    else:
        OUTPUT.write_text(result)
